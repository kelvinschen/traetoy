    companion_navigate(&nav,COMPANION_DOWN,2,0);assert(nav.selected==1);
    companion_navigate(&nav,COMPANION_DOWN,2,0);assert(nav.selected==0);
    companion_navigate(&nav,COMPANION_UP,2,0);assert(nav.selected==1);
    companion_notify(&nav);assert(nav.page==COMPANION_COMPLETE);
    companion_notify(&nav);companion_navigate(&nav,COMPANION_OK,2,1);assert(nav.page==COMPANION_TASKS);
    companion_navigate(&nav,COMPANION_BACK,2,0);assert(nav.page==COMPANION_HOME);
    companion_navigate(&nav,COMPANION_OK,0,0);companion_navigate(&nav,COMPANION_DOWN,0,0);assert(nav.selected==0);
    companion_tile_t tile={0};bool commit=false;
    assert(companion_parse_tile("CDXL|12|2|END",&tile,&commit) && commit && tile.count==2);
    assert(!companion_parse_tile("CDXL|12|17|END",&tile,&commit));
    assert(!companion_parse_tile("CDXL|12|2|ENDbad",&tile,&commit));
    char frame[7168];strcpy(frame,"CDXP|12|0|123|");size_t offset=strlen(frame);
    memset(frame+offset,'a',COMPANION_TILE_BYTES*2);strcpy(frame+offset+COMPANION_TILE_BYTES*2,"|END");
    assert(companion_parse_tile(frame,&tile,&commit) && !commit && tile.pixels[0]==0xaa);
    frame[offset]='z';assert(!companion_parse_tile(frame,&tile,&commit));
    companion_metadata_t meta={0};
    assert(companion_parse_metadata("CDXM|5|20.58M|1.69B|09/05|125|2|123:12,456:3600|END",&meta));
    assert(meta.count==2 && meta.elapsed[1]==3600 && meta.alert_seconds==125);
    assert(!companion_parse_metadata("CDXM|5|--|--|No data|-1|2|123:12|END",&meta));
    assert(!companion_parse_metadata("CDXM|5|--|--|No data|-1|2|123:12,123:13|END",&meta));
    assert(!companion_parse_metadata("CDXM|5|--|--|No data|-1|1|123:-2|END",&meta));
    assert(meta.alert_seconds==125);
    assert(companion_parse_metadata("CDXM|5|--|--|No data|-1|0|-|END",&meta));
    assert(meta.chart[0]==-1 && meta.chart[6]==-1);
    assert(companion_parse_metadata("CDXM|6|2M|7M|09/07|-1|0|-|1|0,100,-1,500,700,900,1000|END",&meta));
    assert(meta.weekday==1 && meta.chart[2]==-1 && meta.chart[6]==1000);
    companion_metadata_t saved=meta;
    assert(!companion_parse_metadata("CDXM|6|2M|7M|09/07|-1|0|-|7|0,1,2,3,4,5,6|END",&meta));
    assert(!companion_parse_metadata("CDXM|6|2M|7M|09/07|-1|0|-|1|0,1,2,3,4,5,1001|END",&meta));
    assert(!companion_parse_metadata("CDXM|6|2M|7M|09/07|-1|0|-|1|0,1,2,3,4,5|END",&meta));
    assert(!companion_parse_metadata("CDXM|6|2M|7M|09/07|-1|0|-|1|0,1,2,3,4,5,6,7|END",&meta));
    assert(!memcmp(&saved,&meta,sizeof(meta)));
    assert(companion_parse_metadata("CDXM|7|20M|1B|Today|-1|0|-|0|0,100,200,300,400,500,921|1.1B|END",&meta));
    assert(!strcmp(meta.ceiling,"1.1B") && meta.chart[6]==921);
    assert(!companion_parse_metadata("CDXM|7|20M|1B|Today|-1|0|-|0|0,100,200,300,400,500,921||END",&meta));
    assert(!companion_parse_metadata("CDXM|7|20M|1B|Today|-1|0|-|0|0,100,200,300,400,500,921|bad|END",&meta));
    assert(companion_parse_metadata("CDXM|8|184M|1.8B|09/06|-1|0|-|0|136,172,219,921,44,18,167|1.1B|150M,189M,241M,1B,48M,20M,184M|31,01,02,03,04,05,06|END",&meta));
    assert(!strcmp(meta.daily[6],"184M") && !strcmp(meta.dates[0],"31"));
    saved=meta;
    assert(!companion_parse_metadata("CDXM|8|184M|1.8B|09/06|-1|0|-|0|136,172,219,921,44,18,167|1.1B|150M,189M,241M,1B,48M,20M,184M|31,01,02,03,04,05,32|END",&meta));
    assert(!companion_parse_metadata("CDXM|8|184M|1.8B|09/06|-1|0|-|0|136,172,219,921,44,18,167|1.1B|150M,189M,241M,1B,48M,20M|31,01,02,03,04,05,06|END",&meta));
    assert(!memcmp(&saved,&meta,sizeof(meta)));
    assert(companion_parse_metadata("CDXM|8|184M|1.8B|09/06|-1|0|-|0|136,172,219,921,44,18,167|1.1B|150M,189M,241M,1B,48M,20M,184M|08/31,09/01,09/02,09/03,09/04,09/05,09/06|END",&meta));
    assert(!strcmp(meta.dates[0],"08/31") && !strcmp(meta.dates[6],"09/06"));
    saved=meta;
    assert(!companion_parse_metadata("CDXM|8|184M|1.8B|09/06|-1|0|-|0|136,172,219,921,44,18,167|1.1B|150M,189M,241M,1B,48M,20M,184M|08/31,09/01,09/02,09/03,09/04,09/05,09/31|END",&meta));
    assert(!companion_parse_metadata("CDXM|8|184M|1.8B|09/06|-1|0|-|0|136,172,219,921,44,18,167|1.1B|150M,189M,241M,1B,48M,20M,184M|08/31,09/01,09/02,09/03,09/04,09/05,13/01|END",&meta));
    assert(!memcmp(&saved,&meta,sizeof(meta)));
    assert(companion_parse_metadata("CDXM|9|184M|1.8B|09/06|-1|0|-|0|136,172,219,921,44,18,167|1.1B|150M,189M,241M,1B,48M,20M,184M|08/31,09/01,09/02,09/03,09/04,09/05,09/06|3|END",&meta));
