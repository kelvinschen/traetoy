    assert(s.remaining[0]==39 && s.remaining[1]==-1 && s.seq==1 && s.alert==1);
    assert(!companion_parse("CDX1|1|101|10080|-1|0|2|3|1|1|x|||END",&s));
    assert(!companion_parse("CDX1|0|39|10080|-1|0|2|3|1|1|x|||END",&s));
    assert(!companion_parse("CDX1|1|39|10080|-1|0|2|3|1|1|x|||END|extra",&s));
