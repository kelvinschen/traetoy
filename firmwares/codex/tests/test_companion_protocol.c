    assert(!memcmp(&saved,&meta,sizeof(meta)));
    assert(companion_parse_metadata("CDXM|5|--|--|No data|-1|0|-|END",&meta));
    assert(meta.reset_cards==-1);
    assert(companion_parse_metadata("CDXM|9|184M|1.8B|09/06|125|0|-|0|136,172,219,921,44,18,167|1.1B|150M,189M,241M,1B,48M,20M,184M|08/31,09/01,09/02,09/03,09/04,09/05,09/06|3|devbox|END",&meta));
