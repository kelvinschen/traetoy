// Lucide 0.468.0, ISC; originals and notice are retained in vendor/lucide.
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {Resvg} from '@resvg/resvg-js';
const root=fileURLToPath(new URL('../',import.meta.url));
const names=['play','coffee','unplug'];
const masks=names.map(name=>{
  const svg=readFileSync(`${root}vendor/lucide/${name}.svg`,'utf8')
    .replace('stroke="currentColor"','stroke="black"').replace('stroke-width="2"','stroke-width="1.8"');
  const pixels=new Resvg(svg,{fitTo:{mode:'width',value:16}}).render().pixels;
  const out=[];
  for(let i=0;i<256;i+=2) out.push((Math.round(pixels[i*4+3]*15/255)<<4)|Math.round(pixels[(i+1)*4+3]*15/255));
  return out;
});
writeFileSync(`${root}main/pet_icons.h`,
  '/* Generated by tools/bake_icons.mjs from Lucide 0.468.0 (ISC).\n * See vendor/lucide/LICENSE. 16x16, 4-bit coverage: play, coffee, unplug. */\n#pragma once\n#include <stdint.h>\nstatic const uint8_t pet_status_icons[3][128] = {\n'+
  masks.map(m=>'  {'+m.join(',')+'}').join(',\n')+'\n};\n');
console.log('Status icons: 3 x 16x16, 384 bytes of antialiased coverage');
