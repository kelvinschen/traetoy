#!/usr/bin/env python3
"""Bake selected 16 kHz mono WAVs into bounded, variable-length flash PCM."""
import argparse
import array
import hashlib
import json
from pathlib import Path
import sys
import wave

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
sources = {s['name']: s for s in json.loads((root / 'assets/sounds/sources.json').read_text())}
text = ['/* Generated by tools/bake_sound.py; do not edit. */', '#include "pet_sound_pcm.h"']
counts = []
for name in ('success', 'failure', 'waiting'):
    source = sources[name]
    path = root / 'assets/sounds' / source['file']
    assert hashlib.sha256(path.read_bytes()).hexdigest() == source['sha256']
    with wave.open(str(path), 'rb') as w:
        assert (w.getnchannels(), w.getsampwidth(), w.getframerate()) == (1, 2, 16000)
        samples = array.array('h', w.readframes(w.getnframes()))
    if sys.byteorder != 'little':
        samples.byteswap()
    assert len(samples) == source['samples'] and max(map(abs, samples)) <= 3000
    assert samples[0] == samples[-1] == 0
    counts.append(len(samples))
    text.append(f'static const int16_t {name}[] = {{')
    for n in range(0, len(samples), 16):
        text.append('  ' + ','.join(map(str, samples[n:n+16])) + ',')
    text.append('};')
text.append('static const pet_sound_t sounds[] = {')
for name, count in zip(('success', 'failure', 'waiting'), counts):
    text.append(f'  {{{name}, {count}u}},')
text.extend(['};', 'const pet_sound_t *pet_sound_get(int kind) {',
             '  return kind >= 1 && kind <= 3 ? &sounds[kind - 1] : 0;', '}'])
output = '\n'.join(text) + '\n'
path = root / 'main/pet_sound_pcm.c'
if args.check:
    assert path.read_text() == output, 'Run tools/bake_sound.py to update flash PCM'
    print('PASS: all three flash PCM clips match the selected WAVs and source hashes')
else:
    path.write_text(output)
